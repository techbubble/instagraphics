// Expand generated families into src/lib/templates-gen.ts and render
// contact sheets for visual review.
//   node scripts/gen/build.mjs [--sheets <dir>] [--only fam1,fam2]
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { Resvg } from "@resvg/resvg-js";
import { HEX, KEYS, wrap } from "./lib.mjs";

const args = process.argv.slice(2);
const opt = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const sheetDir = opt("--sheets");
const only = opt("--only")?.split(",");

const BRAND = { ...HEX };
const contrast = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  const r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
  return (r * 299 + g * 587 + b * 114) / 1000 >= 140 ? "#212529" : "#ffffff";
};
const setAttr = (tag, attr, value) => {
  const re = new RegExp(`\\s${attr}="[^"]*"`);
  return re.test(tag) ? tag.replace(re, ` ${attr}="${value}"`) : tag.replace(/(\s*\/?>)$/, ` ${attr}="${value}"$1`);
};
// Mirror of svg-engine.renderTemplate with the default brand and default text.
function render(svg) {
  return svg.replace(/<[^>]+>/g, (tag) => {
    const f = tag.match(/data-ig-fill="([^"]*)"/); if (f) tag = setAttr(tag, "fill", BRAND[f[1]]);
    const s = tag.match(/data-ig-stroke="([^"]*)"/); if (s) tag = setAttr(tag, "stroke", BRAND[s[1]]);
    const c = tag.match(/data-ig-contrast="([^"]*)"/); if (c) tag = setAttr(tag, "fill", contrast(BRAND[c[1]]));
    const fo = tag.match(/data-ig-font="([^"]*)"/); if (fo) tag = setAttr(tag, "font-family", "Arial");
    return tag;
  });
}

const FONT = { loadSystemFonts: true, defaultFontFamily: "Arial" };

// Fit rendered content into the 900x900 safe area centered on the canvas.
function fit(body) {
  const probe = new Resvg(render(wrap(body)), { font: FONT });
  const bb = probe.getBBox();
  if (!bb || !bb.width || !bb.height) return body;
  const scale = Math.min(900 / bb.width, 900 / bb.height, 1.6);
  const cx = bb.x + bb.width / 2, cy = bb.y + bb.height / 2;
  const tx = 500 - cx * scale, ty = 500 - cy * scale;
  const r2 = (v) => Math.round(v * 100) / 100;
  return `<g transform="translate(${r2(tx)} ${r2(ty)}) scale(${r2(scale)})">\n${body}\n</g>`;
}

const famDir = new URL("./families/", import.meta.url);
const modules = readdirSync(famDir).filter((f) => f.endsWith(".mjs")).sort();
const templates = [];
const familyDescriptions = {};
for (const m of modules) {
  const mod = await import(new URL(m, famDir));
  for (const fam of mod.families) {
    if (only && !only.includes(fam.family)) continue;
    const counts = fam.counts ?? [null];
    const def = fam.defaultCount ?? counts.reduce((b, c) => (Math.abs(c - 4) < Math.abs(b - 4) || (Math.abs(c - 4) === Math.abs(b - 4) && c > b) ? c : b), counts[0]);
    if (counts.length > 1) familyDescriptions[fam.family] = fam.familyDescription ?? fam.description;
    for (const n of counts) {
      const d = fam.draw(n);
      const items = typeof fam.items === "function" ? fam.items(n) : (fam.items ?? n);
      const multi = counts.length > 1;
      const id = `${fam.family}-${multi ? n : 1}`;
      const title = multi ? `${fam.title} (${n} ${fam.unit ?? "items"})` : fam.title;
      const t = {
        id, family: fam.family, title, category: fam.category, items,
        description: typeof fam.description === "function" ? fam.description(n) : fam.description,
        about: fam.about,
        usage: d.usage, labels: d.labels, fieldDefaults: d.fieldDefaults,
        fieldMax: d.fieldMax, fieldOrder: d.fieldOrder,
        defaultVariant: multi && n === def ? true : undefined,
        svg: wrap(fit(d.body)),
      };
      for (const k of Object.keys(t.usage)) if (!KEYS.includes(k)) throw new Error(`${id}: bad key ${k}`);
      templates.push(t);
    }
  }
}

const ids = new Set();
for (const t of templates) { if (ids.has(t.id)) throw new Error(`dup id ${t.id}`); ids.add(t.id); }

if (!only) {
  const out = `// GENERATED by scripts/gen/build.mjs - do not edit by hand.
import type { Template } from "./templates";

export const GENERATED_FAMILY_DESCRIPTIONS: Record<string, string> = ${JSON.stringify(familyDescriptions, null, 2)};

export const GENERATED_TEMPLATES: Template[] = [
${templates.map((t) => {
  const o = { ...t };
  const svg = o.svg; delete o.svg;
  for (const k of Object.keys(o)) if (o[k] === undefined) delete o[k];
  const head = JSON.stringify(o, null, 2).replace(/^/gm, "  ").replace(/\n  }$/, ",\n    svg: `" + svg.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`,\n  }");
  return head;
}).join(",\n")}
];
`;
  writeFileSync(new URL("../../src/lib/templates-gen.ts", import.meta.url), out);
}
console.log(`generated ${templates.length} templates in ${new Set(templates.map((t) => t.family)).size} families`);

// Contact sheets: one PNG per family, variants side by side.
if (sheetDir) {
  mkdirSync(sheetDir, { recursive: true });
  const byFam = new Map();
  for (const t of templates) (byFam.get(t.family) ?? byFam.set(t.family, []).get(t.family)).push(t);
  for (const [fam, list] of byFam) {
    const W = 500;
    const imgs = list.map((t, i) => {
      const png = new Resvg(render(t.svg), { fitTo: { mode: "width", value: W }, font: FONT }).render().asPng();
      return `<image x="${i * (W + 10)}" y="0" width="${W}" height="${W}" href="data:image/png;base64,${Buffer.from(png).toString("base64")}"/>` +
        `<rect x="${i * (W + 10)}" y="0" width="${W}" height="${W}" fill="none" stroke="#999" stroke-width="2"/>` +
        `<text x="${i * (W + 10) + 8}" y="${W - 8}" font-family="Arial" font-size="18" fill="#888">${t.id}</text>`;
    });
    const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="${list.length * (W + 10)}" height="${W}"><rect width="100%" height="100%" fill="#ffffff"/>${imgs.join("")}</svg>`;
    writeFileSync(`${sheetDir}/${fam}.png`, new Resvg(sheet, { font: FONT }).render().asPng());
  }
  console.log(`sheets in ${sheetDir}`);
}
